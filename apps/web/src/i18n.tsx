type Language = keyof typeof messages;
export type MessageKey = keyof (typeof messages)["en"];
const LanguageContext = createContext<{ language: Language; setLanguage: (value: Language) => void; t: (key: MessageKey) => string } | null>(null);

function initialLanguage(): Language {
  const stored = localStorage.getItem("awg-control:language:v1");
  if (stored === "ru" || stored === "en") return stored;
  return navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";
}

export function LanguageProvider({ children }: PropsWithChildren) {
  const [language, setLanguageState] = useState<Language>(initialLanguage);
  const value = useMemo(
    () => ({
      language,
      setLanguage: (next: Language) => {
        localStorage.setItem("awg-control:language:v1", next);
        document.documentElement.lang = next;
        setLanguageState(next);
      },
      t: (key: MessageKey) => messages[language][key],
    }),
    [language],
  );
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("LanguageProvider is missing");
  return value;
}
